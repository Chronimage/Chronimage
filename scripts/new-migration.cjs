#!/usr/bin/env node
// Generate a new SQLx migration file: src-tauri/migrations/<timestamp>_<name>.sql
// Usage: pnpm migrate:new add_source_copies_table

const fs = require('node:fs');
const path = require('node:path');

const name = process.argv[2];
if (!name) {
  console.error('Usage: pnpm migrate:new <snake_case_name>');
  process.exit(1);
}
if (!/^[a-z][a-z0-9_]*$/.test(name)) {
  console.error('Migration name must be snake_case (lowercase + underscores only).');
  process.exit(1);
}

const now = new Date();
const stamp =
  now.getUTCFullYear().toString() +
  String(now.getUTCMonth() + 1).padStart(2, '0') +
  String(now.getUTCDate()).padStart(2, '0') +
  String(now.getUTCHours()).padStart(2, '0') +
  String(now.getUTCMinutes()).padStart(2, '0') +
  String(now.getUTCSeconds()).padStart(2, '0');

const filename = `${stamp}_${name}.sql`;
const target = path.join('src-tauri', 'migrations', filename);

if (fs.existsSync(target)) {
  console.error(`File already exists: ${target}`);
  process.exit(1);
}

const template = `-- Migration: ${name}
-- Created: ${now.toISOString()}
-- Phase: (fill in the phase this supports, e.g. Phase 1 — catalog core)
--
-- Forward-only. Do not edit this file once merged to develop.
-- Paired Rust struct changes go in src-tauri/src/catalog/models.rs.

BEGIN;

-- TODO(cc): write DDL here.

COMMIT;
`;

fs.writeFileSync(target, template);
console.log(`Created ${target}`);
console.log('Update src-tauri/src/catalog/models.rs with matching struct changes.');
